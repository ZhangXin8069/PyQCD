# Run: mpirun -np 4 python3 main.py <resource_path> <cfg_number>
#
# anti-Bs0 -> Ds+  three-point correlator
# Current: bar(c) gamma_x b  (spatial vector)
# Source: anti-Bs0 (anti-s b) with gamma_5 interpolator at t=0
# Sink:   Ds+ (anti-s c)      with gamma_5 interpolator at t=8
# Sequential source constructed from strange spectator propagator.
# Overall sign: + (source-conjugate minus × fermion-loop minus = +)

import os, sys
import numpy as np
import cupy as cp
from opt_einsum import contract
from pyquda_comm import array
from pyquda_utils import core, io, gamma, source

# ═══════════════════════════════════════════════════════════════
# 1. Parameter definitions
# ═══════════════════════════════════════════════════════════════

resource_path = sys.argv[1]
n_cfg = int(sys.argv[2])

# Lattice
latt_size = [24, 24, 24, 72]
grid_size = [1, 1, 1, 4]

# Gauge configuration
cfg_path = (
    "/public/share/weiwang/clqcd/beta6.20_mu-0.2770_ms-0.2400_L24x72"
    "/Configurations/Original/beta6.20_mu-0.2770_ms-0.2400_L24x72_cfg_{n_cfg}.lime"
).format(n_cfg=n_cfg)

# Source / sink
x_src = [0, 0, 0, 0]
t_sink = 8

# Clover action parameters
xi_0 = 1.0
csw  = 1.160920226

# Quark masses (kappa convention: mass = 1/(2*kappa) - 4)
m_s = -0.2356   # strange
m_b =  1.5      # bottom (exploratory — bare am_b ≫ 1, heavy discretisation errors)
m_c =  0.4159   # charm

# Solver parameters
tol         = 1.0e-12
maxiter_s   = 5000    # strange: multigrid CG
maxiter_b   = 2000    # bottom:  standard CG (heavy, fast convergence)
maxiter_c   = 5000    # charm:   standard CG (sequential)

# Multigrid levels: [block_xyzt_level0, block_xyzt_level1, ...]
multigrid = [[6, 6, 6, 3], [4, 4, 4, 6]]

# Gauge link smearing (stout)
stout_nstep = 1
stout_rho   = 0.125
stout_ndim  = 4

# Output
out_path = "C3_antiBs0_to_Dsplus.txt"

# ═══════════════════════════════════════════════════════════════
# 2. Read gauge configuration
# ═══════════════════════════════════════════════════════════════

core.init(grid_size, latt_size, backend="cupy", resource_path=resource_path)
latt_info = core.LatticeInfo(latt_size, t_boundary=-1, anisotropy=1.0)

gauge = io.readChromaQIOGauge(cfg_path)
gauge.toDevice()

# Smeared copy for Dirac inversion; keep raw gauge for potential covariant
gauge_stout = gauge.copy()
gauge_stout.stoutSmear(stout_nstep, stout_rho, stout_ndim)

# ═══════════════════════════════════════════════════════════════
# 3. Construct Dirac operators
# ═══════════════════════════════════════════════════════════════

# Strange: multigrid-preconditioned Clover
dirac_s = core.getDirac(latt_info, m_s, tol, maxiter_s,
                         xi_0, csw, csw, multigrid)

# Bottom: standard CG (heavy quark — rapid convergence, no multigrid needed)
dirac_b = core.getDirac(latt_info, m_b, tol, maxiter_b,
                         xi_0, csw, csw, None)

# Charm: standard CG (sequential solve)
dirac_c = core.getDirac(latt_info, m_c, tol, maxiter_c,
                         xi_0, csw, csw, None)

# ═══════════════════════════════════════════════════════════════
# 4. Compute forward propagators
# ═══════════════════════════════════════════════════════════════

# Point source at spacetime origin
pt_src = source.source12(latt_info, "point", x_src)

# Strange spectator propagator (used for sink block + sequential source)
with dirac_s.useGauge(gauge_stout):
    prop_s = core.invertPropagator(dirac_s, pt_src)

# Bottom forward propagator (current side)
with dirac_b.useGauge(gauge_stout):
    prop_b = core.invertPropagator(dirac_b, pt_src)

# ═══════════════════════════════════════════════════════════════
# 5. Three-point correlator: sequential-source method
#    (einsum strings generated by generate_einsum(type="meson_3pt"))
# ═══════════════════════════════════════════════════════════════

# ------------------------------------------------------------------
# 5a. Gamma matrices on GPU
# ------------------------------------------------------------------
# FROM generate_einsum (meson_3pt)
#   spectator  = s  (prop_s)
#   forward    = b  (prop_b)
#   sequential = c  (prop_seq)
#   sink Gamma = G5   (gamma_5)
#   src  Gamma = G5   (gamma_5)
#   cur  Gamma = g1   (gamma_x, spatial vector current)

I4 = cp.eye(4, dtype=cp.complex128)
G5 = cp.asarray(gamma.gamma(15), dtype=cp.complex128)           # γ₅
Gamma_snk = cp.asarray(gamma.gamma(15), dtype=cp.complex128)    # γ₅ at sink
Gamma_src = cp.asarray(gamma.gamma(15), dtype=cp.complex128)    # γ₅ at source
Gamma_cur = cp.asarray(gamma.gamma(1),  dtype=cp.complex128)    # γ_x (spatial vector current)

# G5-conjugate gammas:  Γ̄ = γ₅ · Γ · γ₅
# These appear in the sink block to convert between the two-dagger convention.
Gamma_snk_bar = G5 @ Gamma_snk @ G5
Gamma_src_bar = G5 @ Gamma_src @ G5

# ------------------------------------------------------------------
# 5b. Sink block  B(x) = Γ̄_snk · S_s(x;0) · Γ̄_src
#     Single Wick topology (meson 3pt — no colour/epsilon sum needed).
# ------------------------------------------------------------------
B = core.LatticePropagator(latt_info)
B.data = contract(
    "AB, wtzyxBCab, CD -> wtzyxADab",
    Gamma_snk_bar, prop_s.data, Gamma_src_bar,
)

# ------------------------------------------------------------------
# 5c. Sequential source at t_sink=8
#     η(x) = γ₅ B† γ₅  =  γ₅ S_s γ₅  =  S_s†(0;x)
# ------------------------------------------------------------------
src_seq = source.sequential12(B, t_sink)

# ------------------------------------------------------------------
# 5d. Sequential inversion (charm propagator from sequential source)
# ------------------------------------------------------------------
with dirac_c.useGauge(gauge_stout):
    prop_seq = core.invertPropagator(dirac_c, src_seq)

# ------------------------------------------------------------------
# 5e. Second dagger:  G̃_seq = γ₅ · G_seq† · γ₅
# ------------------------------------------------------------------
tmp_prop = core.LatticePropagator(latt_info)
tmp_prop.data = contract(
    "AB, wtzyxCBji, CD -> wtzyxADij",
    G5, prop_seq.data.conj(), G5,
)

# ------------------------------------------------------------------
# 5f. Final contraction:  C3(τ) = + Σ_z Tr[ G̃_seq(z,τ) · γ_x · S_b(z,τ;0) ]
#     Contract all spatial, spin, colour indices → function of τ only.
#     The overall sign of +1 is built into the sink block definition.
# ------------------------------------------------------------------
three_pt_local = contract(
    "wtzyxijba, jk, wtzyxkiab -> t",
    tmp_prop.data, Gamma_cur, prop_b.data,
)

# ═══════════════════════════════════════════════════════════════
# 6. MPI gather and save
# ═══════════════════════════════════════════════════════════════

C3_t = core.gatherLattice(
    array.arrayAsNumpy(three_pt_local, backend="cupy"),
    [0, -1, -1, -1],
)

if core.getMPIRank() == 0:
    C3_real = np.asarray(C3_t, dtype=np.complex128).real.reshape(-1)
    tau = np.arange(C3_real.shape[0], dtype=np.int32)
    out = np.column_stack((tau, C3_real))
    np.savetxt(out_path, out, fmt=["%d", "%.16e"])