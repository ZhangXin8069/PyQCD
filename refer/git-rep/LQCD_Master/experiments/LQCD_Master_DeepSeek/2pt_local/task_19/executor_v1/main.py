import os, sys
import numpy as np
import cupy as cp
from opt_einsum import contract
from pyquda_comm import array
from pyquda_utils import core, io, gamma, source

# ==============================================================================
# Parameters -- Xi_cc (dcc) doubly-charmed baryon two-point function
# ==============================================================================

resource_path = sys.argv[1]
n_cfg = sys.argv[2]

latt_size = [24, 24, 24, 72]
grid_size = [1, 1, 1, 4]

cfg_path = "/public/share/weiwang/clqcd/beta6.20_mu-0.2770_ms-0.2400_L24x72/Configurations/Original/beta6.20_mu-0.2770_ms-0.2400_L24x72_cfg_{n_cfg}.lime".format(n_cfg=n_cfg)

x_src = [0, 0, 0, 0]

xi_0 = 1.0
csw = 1.160920226

m_l = -0.277
m_c = 0.4159

tol = 1.0e-8
maxiter_l = 10000
maxiter_c = 20000
multigrid = [[6, 6, 6, 3], [4, 4, 4, 6]]

stout_nstep = 1
stout_rho = 0.125
stout_ndim = 4

# ==============================================================================
# Initialize PyQUDA
# ==============================================================================

core.init(grid_size, latt_size, backend="cupy", resource_path=resource_path)
latt_info = core.LatticeInfo(latt_size, t_boundary=-1, anisotropy=1.0)

# ==============================================================================
# Read gauge configuration and apply stout smearing
# ==============================================================================

gauge = io.readChromaQIOGauge(cfg_path)
gauge.toDevice()
gauge_stout = gauge.copy()
gauge_stout.stoutSmear(stout_nstep, stout_rho, stout_ndim)

# ==============================================================================
# Construct Dirac operators
#   Light quark (d): multigrid solver for near-critical mass
#   Charm quark (c): CG solver -- multigrid coarse-grid is tuned for light quarks
# ==============================================================================

dirac_l = core.getDirac(latt_info, m_l, tol, maxiter_l, xi_0, csw, csw, multigrid)
dirac_c = core.getDirac(latt_info, m_c, tol, maxiter_c, xi_0, csw, csw, None)

# ==============================================================================
# Compute forward propagators (point source at origin)
# ==============================================================================

pt_src = source.source12(latt_info, "point", x_src)

with dirac_l.useGauge(gauge_stout):
    prop_l = core.invertPropagator(dirac_l, pt_src)

with dirac_c.useGauge(gauge_stout):
    prop_c = core.invertPropagator(dirac_c, pt_src)

# ==============================================================================
# Gamma matrices and tensors (on GPU for einsum contraction)
#   Cg5 = C @ gamma_5  (scalar diquark for 1/2+ ground state)
#   Tmat = (1 + gamma_4) / 2  (positive-parity projector P+)
# ==============================================================================

G5 = cp.asarray(gamma.gamma(15), dtype=cp.complex128)
Cmat = cp.asarray(gamma.gamma(2) @ gamma.gamma(8), dtype=cp.complex128)
Cg5 = Cmat @ G5
g4 = cp.asarray(gamma.gamma(8), dtype=cp.complex128)
Tmat = (cp.eye(4, dtype=cp.complex128) + g4) * 0.5

epsilon = cp.zeros((3, 3, 3), dtype=cp.complex128)
epsilon[0,1,2] = epsilon[1,2,0] = epsilon[2,0,1] = 1.0
epsilon[0,2,1] = epsilon[2,1,0] = epsilon[1,0,2] = -1.0

# ==============================================================================
# Contraction: Xi_cc baryon two-point correlator
#   Generated by generate_einsum(type="baryon_2pt", quark_a="light",
#   quark_b="charm", quark_c="charm", diquark_gamma="Cg5", projector="P_plus")
#
# Two Wick topologies because the two charm quarks at slots b,c are identical.
#   Topo 0 (direct):  standard diquark pairing, sign = -1
#   Topo 1 (exchange): charm quarks b<->c swapped, sign = +1
# The light-quark propagator S_l is identical in both terms.
# ==============================================================================

C_t_local = 0

# Topology 0: direct term
C_t_local += -contract(
    'AB, abc, EF, efd, CD, wtzyxDAda, wtzyxFCfc, wtzyxEBeb -> t',
    Cg5, epsilon, Cg5, epsilon, Tmat,
    prop_c.data, prop_c.data, prop_l.data
)

# Topology 1: exchange term (b <-> c)
C_t_local += contract(
    'AB, abc, EF, efd, CD, wtzyxDCdc, wtzyxFAfa, wtzyxEBeb -> t',
    Cg5, epsilon, Cg5, epsilon, Tmat,
    prop_c.data, prop_c.data, prop_l.data
)

# ==============================================================================
# MPI gather: sum correlator across spatial ranks to rank 0
# ==============================================================================

C_t = core.gatherLattice(array.arrayAsNumpy(C_t_local, backend="cupy"), [0, -1, -1, -1])

# ==============================================================================
# Save result: real part only, one value per time slice, no header
# ==============================================================================

if core.getMPIRank() == 0:
    C_t_real = np.asarray(C_t, dtype=np.complex128).reshape(-1).real
    out_name = "xi_cc_2pt_cfg{n_cfg}.txt".format(n_cfg=n_cfg)
    np.savetxt(out_name, C_t_real, fmt="%.16e")
