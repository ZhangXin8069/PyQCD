# Ξ_c → Ξ three-point function via c→s vector current (γ_x)
# Source:    Ξ_c (dsc) at t=0,  ε^{abc}(d^T Cγ₅ s^b) c^c
# Sink:      Ξ   (dss) at t=8,  ε^{def}(d^T Cγ₅ s^e) s^f
# Current:   s̄ γ_x c  (vector, γ₁ in DeGrand-Rossi)
# Projector: T = (I + γ₄)/2  (positive parity)
# Sequential source method, two-dagger convention.
# Point source [0,0,0,0], zero momentum, stout smearing (1, 0.125, 4).
# Only the 3pt correlator is computed; no 2pt function.

import os, sys
import numpy as np
import cupy as cp
from opt_einsum import contract
from pyquda_comm import array
from pyquda_utils import core, io, gamma, source

# ═══════════════════════════════════════════════════════════════
# 1. Parameter definitions (hard-coded)
# ═══════════════════════════════════════════════════════════════

resource_path = sys.argv[1]          # QUDA tunecache directory
n_cfg = sys.argv[2]                  # configuration number, e.g. "10000"

latt_size = [24, 24, 24, 72]
grid_size = [1, 1, 1, 4]             # 4 MPI ranks in time direction

cfg_path_template = (
    "/public/share/weiwang/clqcd/beta6.20_mu-0.2770_ms-0.2400_L24x72"
    "/Configurations/Original/beta6.20_mu-0.2770_ms-0.2400_L24x72_cfg_{n_cfg}.lime"
)

# Source
x_src = [0, 0, 0, 0]                 # point source at origin
t_seq = 8                            # sink time slice

# Gauge action
xi_0 = 1.0
csw  = 1.160920226

# Quark masses (Wilson-Clover, kappa convention via mass parameter)
m_l = -0.277                         # light (d)
m_s = -0.2356                        # strange
m_c = 0.4159                         # charm

# Solver parameters
tol       = 1.0e-12
maxiter   = 10000
maxiter_c = 20000                    # more iterations for heavy charm
multigrid = [[6, 6, 6, 3], [4, 4, 4, 6]]

# Stout link smearing
stout_nstep = 1
stout_rho   = 0.125
stout_ndim  = 4

# Output
out_path = "xic_to_xi_3pt_vx_result.txt"

# ═══════════════════════════════════════════════════════════════
# 2. Read gauge configuration
# ═══════════════════════════════════════════════════════════════

core.init(grid_size, latt_size, backend="cupy", resource_path=resource_path)
latt_info = core.LatticeInfo(latt_size, t_boundary=-1, anisotropy=1.0)

cfg_path = cfg_path_template.format(n_cfg=n_cfg)
gauge = io.readChromaQIOGauge(cfg_path)
gauge.toDevice()

gauge_stout = gauge.copy()
gauge_stout.stoutSmear(stout_nstep, stout_rho, stout_ndim)

# ═══════════════════════════════════════════════════════════════
# 3. Construct Dirac operators
# ═══════════════════════════════════════════════════════════════

dirac_l = core.getDirac(latt_info, m_l, tol, maxiter,   xi_0, csw, csw, multigrid)
dirac_s = core.getDirac(latt_info, m_s, tol, maxiter,   xi_0, csw, csw, multigrid)
# Charm: heavy quark converges without multigrid; BiCGStab is used (CGNE
# would also work, but BiCGStab is the default when multigrid=None).
dirac_c = core.getDirac(latt_info, m_c, tol, maxiter_c, xi_0, csw, csw, None)

# ═══════════════════════════════════════════════════════════════
# 4. Compute forward propagators (point source, stout-smeared gauge)
# ═══════════════════════════════════════════════════════════════

pt_src = source.source12(latt_info, "point", x_src)

with dirac_l.useGauge(gauge_stout):
    prop_l = core.invertPropagator(dirac_l, pt_src)

with dirac_s.useGauge(gauge_stout):
    prop_s = core.invertPropagator(dirac_s, pt_src)

with dirac_c.useGauge(gauge_stout):
    prop_c = core.invertPropagator(dirac_c, pt_src)

# ═══════════════════════════════════════════════════════════════
# 5. Extract observable / compute contraction (baryon 3pt)
# ═══════════════════════════════════════════════════════════════

# ── Gamma matrices and tensors on GPU ──
I4 = cp.eye(4, dtype=cp.complex128)
G5 = cp.asarray(gamma.gamma(15), dtype=cp.complex128)              # γ₅
Gamma_cur = cp.asarray(gamma.gamma(1), dtype=cp.complex128)        # γ₁ (γ_x)

# Levi-Civita ε_{abc}
eps = cp.zeros((3, 3, 3), dtype=cp.complex128)
eps[0,1,2] = eps[1,2,0] = eps[2,0,1] = 1.0
eps[0,2,1] = eps[2,1,0] = eps[1,0,2] = -1.0

# Charge conjugation and projector
Cmat = cp.asarray(gamma.gamma(2) @ gamma.gamma(8), dtype=cp.complex128)
Cg5  = Cmat @ G5                                                 # Cγ₅
Tmat = cp.asarray((I4 + gamma.gamma(8)) * 0.5, dtype=cp.complex128)  # P_plus

# ── Sink block B(x) at t=8 (Ξ: dss) ──
# Two Wick topologies (s̄→s^e and s̄→s^f); both add with same sign.
# Einsum strings generated by generate_einsum(baryon_3pt).

B = core.LatticePropagator(latt_info)
B.data = (
    - contract(
        'AB,abi,GK,fje,JF,wtzyxFAea,wtzyxGBfb->wtzyxJKij',
        Cg5, eps, Cg5, eps, Tmat, prop_s.data, prop_l.data,
    )   # topology 0: s̄ in current attaches to s^f (external s)
    + contract(
        'AB,abi,GH,fgj,JK,wtzyxHAga,wtzyxGBfb->wtzyxJKij',
        Cg5, eps, Cg5, eps, Tmat, prop_s.data, prop_l.data,
    )   # topology 1: s̄ in current attaches to s^e (diquark s)
)

# First dagger:  η_seq = γ₅ B† γ₅
B.data = contract(
    'AB, wtzyxCBji, CD -> wtzyxADij',
    G5, B.data.conj(), G5)

# Sequential source at t_sink = 8
src_seq = source.sequential12(B, t_seq)

# Sequential solve for strange quark (D_s · G_seq = η_seq)
with dirac_s.useGauge(gauge_stout):
    prop_seq = core.invertPropagator(dirac_s, src_seq)

# Second dagger on sequential propagator
G_seq_dag = core.LatticePropagator(latt_info)
G_seq_dag.data = contract(
    'AB, wtzyxCBji, CD -> wtzyxADij',
    G5, prop_seq.data.conj(), G5)

# ── Final contraction: C₃(τ) = Σ_{z} Tr[ G_seq_dag · γ_x · S_c ] ──
three_pt_local = contract(
    'wtzyxijba, jk, wtzyxkiab -> t',
    G_seq_dag.data, Gamma_cur, prop_c.data,
)

# MPI gather to rank 0
C3_t = core.gatherLattice(three_pt_local.get(), [0, -1, -1, -1])

# ═══════════════════════════════════════════════════════════════
# 6. Save the result (τ = 0 .. t_seq, two columns: Re, Im)
# ═══════════════════════════════════════════════════════════════

if core.getMPIRank() == 0:
    C3_window = np.asarray(C3_t[:t_seq+1], dtype=np.complex128)
    # Each line:  real_part  imag_part   (no header, no tau column)
    np.savetxt(
        out_path,
        np.column_stack((C3_window.real, C3_window.imag)),
        fmt=["%.16e", "%.16e"],
    )
